let currentLang = localStorage.getItem('language') || 'en';
let listeners = [];

// ============================================================
// SET LANGUAGE
// ============================================================
export function setLanguage(lang) {
    if (!TRANSLATIONS[lang]) {
        console.warn(`⚠️ Language "${lang}" not supported, falling back to English`);
        lang = 'en';
    }
    
    currentLang = lang;
    localStorage.setItem('language', lang);
    
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.dataset.i18n;
        const translation = translate(key);
        if (translation !== key) {
            if (el.tagName === 'INPUT' && el.type === 'text') return;
            if (el.tagName === 'TEXTAREA') return;
            
            if (el.tagName === 'H1' || el.tagName === 'H2' || el.tagName === 'H3' || 
                el.tagName === 'H4' || el.tagName === 'H5' || el.tagName === 'H6') {
                el.innerHTML = translation;
            } else if (el.tagName === 'BUTTON') {
                const textNode = el.querySelector('.btn-text');
                if (textNode) textNode.textContent = translation;
                else if (!el.querySelector('svg') && !el.querySelector('.spinner')) el.textContent = translation;
            } else if (el.tagName === 'LABEL') {
                if (!el.querySelector('a') && !el.querySelector('input')) el.textContent = translation;
            } else {
                el.textContent = translation;
            }
        }
    });
    
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.dataset.i18nPlaceholder;
        const translation = translate(key);
        if (translation !== key) el.placeholder = translation;
    });
    
    const flag = document.getElementById('currentLangFlag');
    const label = document.getElementById('currentLangLabel');
    if (flag) flag.textContent = getLangFlag(lang);
    if (label) label.textContent = lang.toUpperCase();
    
    document.querySelectorAll('#langDropdown button').forEach(btn => {
        btn.classList.toggle('active', btn.dataset.lang === lang);
    });
    
    listeners.forEach(callback => callback(lang));
    window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
    
    console.log(`🌐 Language changed to: ${lang}`);
}

// ============================================================
// TRANSLATE
// ============================================================
export function translate(key, lang = currentLang) {
    const translations = TRANSLATIONS[lang];
    if (!translations) return key;
    return translations[key] || key;
}

// ============================================================
// HELPERS
// ============================================================
export function getLangFlag(lang) {
    const flags = { en: '🇬🇧', sw: '🇹🇿', fr: '🇫🇷' };
    return flags[lang] || '🌐';
}

export function getLangName(lang) {
    const names = { en: 'English', sw: 'Kiswahili', fr: 'Français' };
    return names[lang] || lang;
}

export function getSupportedLanguages() {
    return Object.keys(TRANSLATIONS);
}

export function addLanguageListener(callback) {
    listeners.push(callback);
}

// ============================================================
// INIT LANGUAGE
// ============================================================
export function initLanguage() {
    console.log('🌐 Initializing language system...');
    
    const savedLang = localStorage.getItem('language');
    const browserLang = navigator.language.split('-')[0];
    const supported = getSupportedLanguages();
    
    let defaultLang = 'en';
    if (savedLang && supported.includes(savedLang)) defaultLang = savedLang;
    else if (supported.includes(browserLang)) defaultLang = browserLang;
    
    setLanguage(defaultLang);
    console.log(`✅ Language system initialized (Current: ${currentLang})`);
}

